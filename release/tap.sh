#!/usr/bin/env bash
# Point the Homebrew tap at a published release.
#
#   release/tap.sh v1.0.0
#
# Clones the tap (github.com/imaustink/homebrew-ferry, or FERRY_TAP_REPO) into a
# temporary directory, writes Formula/ferry.rb from release/homebrew.sh, and
# commits and pushes it. cut.sh runs this after a live publish. It is never run
# for a draft: the formula would point at a tarball nobody can download, and
# 'brew install' would fail for everyone until the draft went live.
#
# Idempotent: a formula already at this version is left alone.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"

ok()  { printf '  \033[32m✓\033[0m %s\n' "$1"; }
die() { printf '  \033[31m✗\033[0m %s\n' "$1" >&2; exit 1; }

version="${1:-}"
case "$version" in v[0-9]*.[0-9]*.[0-9]*) : ;; *) die "usage: release/tap.sh vX.Y.Z" ;; esac
tap="${FERRY_TAP_REPO:-imaustink/homebrew-ferry}"

formula="$("$here/homebrew.sh" "$version")" || die "could not generate the formula for $version"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
# owner/name through gh, which carries the credentials to push; a path or URL
# (a local bare repository, in tests) with git itself.
case "$tap" in
  /*|*://*) git clone --quiet "$tap" "$work/tap" 2>/dev/null || die "could not clone $tap" ;;
  *)        gh repo clone "$tap" "$work/tap" -- --quiet 2>/dev/null || die "could not clone $tap" ;;
esac
cd "$work/tap"

mkdir -p Formula
if [ -f Formula/ferry.rb ] && [ "$(cat Formula/ferry.rb)" = "$formula" ]; then
  ok "$tap already has ferry $version"
  exit 0
fi
printf '%s\n' "$formula" > Formula/ferry.rb

# An empty tap gets a README the first time, so the repository says what it is.
if [ ! -f README.md ]; then
  cat > README.md <<'EOF'
# homebrew-ferry

The Homebrew tap for [ferry](https://github.com/imaustink/ferry): Kubernetes on
a Mac, one virtual machine per pod.

```sh
brew install imaustink/ferry/ferry
ferry up
```

`Formula/ferry.rb` is generated by `release/homebrew.sh` in the ferry
repository at every release. Change that, not this.
EOF
fi

git add Formula/ferry.rb README.md
git commit --quiet -m "ferry ${version#v}"
# An empty repository has no branch yet; main is the one to create.
git push --quiet origin HEAD:main || die "could not push to $tap"
ok "$tap: ferry ${version#v}"
echo "  brew install imaustink/ferry/ferry"
