#!/usr/bin/env bash
# Print the Homebrew formula for a release, to commit to the tap
# (github.com/imaustink/homebrew-ferry, as Formula/ferry.rb):
#
#   release/homebrew.sh v1.0.0      # print it; release/tap.sh commits it
#   brew install imaustink/ferry/ferry
#
# The sha256 is read from dist/ when the release was built on this Mac, and
# fetched from the release's published .sha256 otherwise. FERRY_FORMULA_URL
# replaces the download URL, for testing the formula against a local tarball
# (a file:// URL works), and FERRY_FORMULA_SHA256 its checksum.
#
# Two things about the formula are deliberate:
#
#   - ferry is not symlinked into bin. ferry finds its own files by following
#     the symlink it was run through, so a symlink would resolve into
#     Cellar/ferry/<version>/ and the LaunchAgent would record that path --
#     which 'brew upgrade' then deletes. bin/ferry is instead a two-line script
#     that runs opt/ferry/libexec/ferry, and opt/ferry is the path Homebrew
#     keeps pointing at whichever version is installed. That is the same job
#     ~/.ferry-dist/current does for the curl installer.
#   - Nothing is started. 'ferry up' is the next step, as it is for kind.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
version="${1:-}"
case "$version" in v[0-9]*.[0-9]*.[0-9]*) : ;; *) echo "usage: release/homebrew.sh vX.Y.Z" >&2; exit 2 ;; esac

repo="${FERRY_REPO:-imaustink/ferry}"
tarball="ferry-$version-darwin-arm64.tar.gz"
url="${FERRY_FORMULA_URL:-https://github.com/$repo/releases/download/$version/$tarball}"
if [ -n "${FERRY_FORMULA_SHA256:-}" ]; then
  sha="$FERRY_FORMULA_SHA256"
elif [ -f "$root/dist/$tarball.sha256" ]; then
  sha="$(awk '{print $1}' "$root/dist/$tarball.sha256")"
else
  sha="$(curl -sfL "https://github.com/$repo/releases/download/$version/$tarball.sha256" | awk '{print $1}')"
fi
[ "${#sha}" -eq 64 ] || { echo "no sha256 for $tarball" >&2; exit 1; }

cat <<EOF
# Generated by release/homebrew.sh in $repo. Edit that, not this.
class Ferry < Formula
  desc "Kubernetes on a Mac, one virtual machine per pod"
  homepage "https://github.com/$repo"
  url "$url"
  version "${version#v}"
  sha256 "$sha"
  license "MIT"

  depends_on arch: :arm64
  depends_on macos: :tahoe
  depends_on "kubernetes-cli"

  def install
    libexec.install Dir["*"]
    # A script, not a symlink: see release/homebrew.sh.
    (bin/"ferry").write <<~SH
      #!/bin/sh
      exec "#{opt_libexec}/ferry" "\$@"
    SH
    chmod 0755, bin/"ferry"
    generate_completions_from_executable(libexec/"ferry", "completion")
  end

  def caveats
    <<~EOS
      Start a cluster:          ferry up
      Start it at every login:  ferry service install
    EOS
  end

  test do
    assert_match "ferry v#{version}", shell_output("#{bin}/ferry version")
    assert_match "complete -F _ferry ferry", shell_output("#{bin}/ferry completion bash")
  end
end
EOF
